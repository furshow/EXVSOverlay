# Generates src/unit_names.h (unit id -> display name) from the game's own unit-name table, read with the
# EXVSIB Mod Manager's code (its translation, if installed, is what you get).
# Usage: py tools/make_unit_names.py "<game folder>\data\x64\dplcache_release" [Mod Manager src folder]
import os, sys
data = sys.argv[1]
mm = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', '..', 'EXVSModManager', 'src')
sys.path[:0] = [os.path.join(mm, d) for d in ('app', 'formats', 'extract', 'modding', 'translation', 'online', 'blender')]
import catalog

units = catalog.names(data)[0]
rows = []
for uid in sorted(units):
    name = (units[uid][0] or '').strip()
    if name and all(32 <= ord(c) < 127 for c in name):
        rows.append('    { %d, "%s" },' % (uid, name.replace('\\', '\\\\').replace('"', '\\"')))
out = os.path.join(os.path.dirname(__file__), '..', 'src', 'unit_names.h')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/make_unit_names.py from the game data (unit id -> name). Do not edit.\n#pragma once\n')
    f.write('static const struct { unsigned id; const char *name; } UNIT_NAMES[] = {\n%s\n};\n' % '\n'.join(rows))
print(len(rows), 'names ->', os.path.normpath(out))
