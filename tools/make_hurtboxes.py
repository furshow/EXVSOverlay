# Generates src/unit_hurtboxes.h: for every playable unit, its hurt spheres (body bone index in the live bone array,
# offset in that bone's space, radius) and the body skeleton's bone count, read with the EXVSIB Mod Manager's code.
# Usage: py tools/make_hurtboxes.py "<game folder>\data\x64\dplcache_release" [Mod Manager src folder]
import os, sys, struct, re
data = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
mm = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', '..', 'EXVSModManager', 'src')
sys.path[:0] = [os.path.join(mm, d) for d in ('app', 'formats', 'extract', 'modding', 'translation', 'online', 'blender')]
from fhm2d import Fhm2d
import hitboxes, model_blender

ids_wanted = [int(m) for m in re.findall(r'\{ (\d+), "', open(os.path.join(here, '..', 'src', 'unit_names.h'), encoding='utf-8').read())]


def read(fid):
    p = os.path.join(data, '0x%08X.fhm2d' % fid)
    return open(p, 'rb').read() if os.path.exists(p) else None


d = Fhm2d(read(0x036B9E67)).subfile(0)
n, st = struct.unpack_from('<II', d, 0x10)
index = dict((u, i) for i, u in enumerate(struct.unpack_from('<%dI' % n, d, 0x20)))
units, spheres, fails = [], [], 0
for uid in ids_wanted:
    if uid not in index:
        continue
    model, _e, _s, params, _sc, _a = struct.unpack_from('<6I', d, 0x20 + 4 * n + st * index[uid])
    raw, praw = read(model), read(params)
    if not raw or not praw:
        continue
    try:
        parts = model_blender.pieces(raw)[0]
        order = [b for b, _ in model_blender.body_part(parts)['parents']]
        hurt = hitboxes.hurt_spheres(praw, uid, raw, parts)
    except Exception as e:
        fails += 1
        continue
    rows = [(order.index(h['bone']), h['offset'], h['radius']) for h in hurt if h['bone'] in order]
    if not rows:
        continue
    units.append((uid, len(order), len(spheres), len(rows)))
    spheres += rows
out = os.path.join(here, '..', 'src', 'unit_hurtboxes.h')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/make_hurtboxes.py from the game data. Do not edit.\n#pragma once\n')
    f.write('struct HurtSphere { unsigned char bone; float x, y, z, r; };\n')
    f.write('struct HurtUnit { unsigned id; unsigned short nbones, first, count; };\n')
    f.write('static const HurtSphere HURT_SPHERES[] = {\n%s\n};\n' % '\n'.join(
        '    { %d, %.4ff, %.4ff, %.4ff, %.4ff },' % (b, o[0], o[1], o[2], r) for b, o, r in spheres))
    f.write('static const HurtUnit HURT_UNITS[] = {   // sorted by id\n%s\n};\n' % '\n'.join(
        '    { %d, %d, %d, %d },' % u for u in units))
print('%d units, %d spheres, %d failed -> %s' % (len(units), len(spheres), fails, os.path.normpath(out)))
