# Generates src/unit_projectiles.h: for every playable unit, the rows of its projectile table (params, the table
# with the hit column 89be0f56): row id and the two size columns. Live hits of the beam rifle (speed column
# ff51e424 = 7.2, measured) stop within 0.8 of the hurt spheres, charge shots (speed 10) within ~2: column ab606d9e.
# Live projectiles do not keep their row id. Units with an action table name the projectile of each shot in its
# record (+0x74 / +0x7c): table action hash -> size, used with the move the unit is doing when the shot appears.
# Otherwise the overlay matches the measured speed.
# Usage: py tools/make_projectiles.py "<game folder>\data\x64\dplcache_release" [Mod Manager src folder]
import os, sys, struct, re
data = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
mm = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', '..', 'EXVSModManager', 'src')
sys.path[:0] = [os.path.join(mm, d) for d in ('app', 'formats', 'extract', 'modding', 'translation', 'online', 'blender')]
from fhm2d import Fhm2d
import hitboxes as H

C_SIZE_A, C_SIZE_B, C_SPEED = 0xab606d9e, 0xaf2b7098, 0xff51e424
ids_wanted = [int(m) for m in re.findall(r'\{ (\d+), "', open(os.path.join(here, '..', 'src', 'unit_names.h'), encoding='utf-8').read())]


def read(fid):
    p = os.path.join(data, '0x%08X.fhm2d' % fid)
    return open(p, 'rb').read() if os.path.exists(p) else None


d = Fhm2d(read(0x036B9E67)).subfile(0)
n, st = struct.unpack_from('<II', d, 0x10)
index = dict((u, i) for i, u in enumerate(struct.unpack_from('<%dI' % n, d, 0x20)))
units, rows, acts = [], [], []


def row_size(a, b):
    return a if 0 < a <= 30 else b if b > 0 else 0.0

for uid in sorted(ids_wanted):
    if uid not in index:
        continue
    _m, _e, _s, params, _sc, _a = struct.unpack_from('<6I', d, 0x20 + 4 * n + st * index[uid])
    praw = read(params)
    if not praw:
        continue
    try:
        tables, actions = H.read_params(praw, uid)
    except Exception:
        continue
    projs = next((t for t in tables.values() if H.C_PROJ_HIT in t.cols and C_SIZE_A in t.cols and C_SIZE_B in t.cols), None)
    if projs is None:
        continue
    rs = sorted((r, projs.get(r, C_SIZE_A, '<f'), projs.get(r, C_SIZE_B, '<f'), projs.get(r, C_SPEED, '<f') if C_SPEED in projs.cols else 0.0) for r in projs.ids)
    size_of = dict((r, row_size(a, b)) for r, a, b, _sp in rs)
    speed_of = dict((r, sp) for r, _a, _b, sp in rs)
    am = {}
    for rec in actions:
        h = rec[0xb4 // 4]
        if not h or h in am:
            continue
        for v in rec:
            if v in projs.row:
                z = size_of.get(v, 0)
                if not z:                                   # a parent without its own size: its first child with one
                    for c in H.C_PROJ_CHILDREN:
                        ch = projs.get(v, c) if c in projs.cols else 0
                        if ch in size_of and size_of[ch]:
                            z = size_of[ch]; break
                if z:
                    am[h] = (z, speed_of.get(v, 0.0)); break
    act = sorted((h, z, sp) for h, (z, sp) in am.items())
    units.append((uid, len(rows), len(rs), len(acts), len(act)))
    rows += rs
    acts += act
out = os.path.join(here, '..', 'src', 'unit_projectiles.h')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/make_projectiles.py from the game data. Do not edit.\n#pragma once\n')
    f.write('struct ProjRow { unsigned id; float a, b, speed; };   // projectile table row: id, size columns ab606d9e / af2b7098, speed ff51e424\n')
    f.write('struct ProjUnit { unsigned id; unsigned first, count, act_first, act_count; };\n')
    f.write('struct ProjAct { unsigned hash; float size, speed; };   // shot action -> size and speed of its projectile\n')
    f.write('static const ProjAct PROJ_ACTS[] = {   // sorted by hash within each unit\n%s\n};\n' % '\n'.join(
        '    { 0x%08x, %.3ff, %.3ff },' % a for a in acts))
    f.write('static const ProjRow PROJ_ROWS[] = {   // sorted by id within each unit\n%s\n};\n' % '\n'.join(
        '    { 0x%08x, %.3ff, %.3ff, %.3ff },' % r for r in rows))
    f.write('static const ProjUnit PROJ_UNITS[] = {   // sorted by id\n%s\n};\n' % '\n'.join('    { %d, %d, %d, %d, %d },' % u for u in units))
print('%d units, %d projectile rows, %d shot actions -> %s' % (len(units), len(rows), len(acts), os.path.normpath(out)))
